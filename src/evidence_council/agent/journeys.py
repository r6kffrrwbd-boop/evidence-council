"""Customer journeys with k6: scripted personas, browser tests and light HTTP load.

Personas are declarative JSON in the plan (steps such as goto / fill / click /
expect_text, or HTTP requests). This module renders each persona into a k6 script
deterministically — the step data is embedded as JSON, never spliced into code — and the
rendered scripts are part of what you approve (their hash is in the plan fingerprint).

Safety: scripts only ever target the local app the run starts itself (``EC_BASE_URL``,
always ``http://127.0.0.1:<port>``). Load is capped at 20 virtual users for 60 seconds.

What is detected
----------------
* failed steps / checks, with the page text or HTTP status that failed;
* hanging or slow requests: per-step timeouts and ``max_request_ms`` on the slowest request;
* unintended repeated work: more requests per journey than ``max_requests`` allows
  (for example a page that re-fetches the same data in a loop).
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

BROWSER_TEMPLATE = r"""// Generated by evidence-council from persona "%(id)s" (%(name)s). Review before approving.
import { browser } from 'k6/browser';
import { check } from 'k6';

export const options = {
  scenarios: { journey: { executor: 'shared-iterations', vus: 1, iterations: 1, maxDuration: '%(max_duration)ss',
                          options: { browser: { type: 'chromium' } } } },
};

const BASE = __ENV.EC_BASE_URL;          // set by evidence-council: always http://127.0.0.1:<port>
const STEPS = %(steps)s;

export default async function () {
  const page = await browser.newPage();
  const results = [];
  const requests = [];                    // every request the page made: url, ms, status (for repeated/hanging-work reports)
  try {
    page.on('request', (req) => { requests.push({ url: req.url(), t0: Date.now(), ms: null, status: null }); });
    page.on('response', (res) => {
      const r = requests.find((x) => x.url === res.url() && x.status === null);
      if (!r) return;
      r.status = res.status();
      r.wall_ms = Date.now() - r.t0;       // includes browser start-up and queueing
      r.ms = r.wall_ms;
      try {                                // request sent -> first response byte, as the browser measured it
        const t = res.request().timing();
        if (t && t.requestStart >= 0 && t.responseStart >= t.requestStart) { r.ms = t.responseStart - t.requestStart; }
      } catch (e) { /* timing unavailable: keep wall time */ }
    });
  } catch (e) { /* older k6: request details unavailable; counts still come from metrics */ }
  try {
    for (const s of STEPS) {
      const t0 = Date.now();
      let ok = true;
      let detail = '';
      try {
        if (s.action === 'goto') {
          await page.goto(BASE + s.path, { waitUntil: 'networkidle', timeout: s.timeout_ms });
        } else if (s.action === 'fill') {
          await page.locator(s.selector).fill(s.value, { timeout: s.timeout_ms });
        } else if (s.action === 'click') {
          await page.locator(s.selector).click({ timeout: s.timeout_ms });
        } else if (s.action === 'wait_for') {
          await page.locator(s.selector).waitFor({ state: 'visible', timeout: s.timeout_ms });
        } else if (s.action === 'expect_text') {
          const loc = page.locator(s.selector);
          await loc.waitFor({ state: 'visible', timeout: s.timeout_ms });
          const deadline = Date.now() + s.timeout_ms;
          let txt = '';
          while (Date.now() < deadline) {
            txt = (await loc.textContent()) || '';
            if (txt.includes(s.contains)) break;
            await page.waitForTimeout(100);
          }
          ok = txt.includes(s.contains);
          detail = 'text was: ' + txt.slice(0, 200);
        }
      } catch (e) {
        ok = false;
        detail = String(e).slice(0, 300);
      }
      results.push({ step: s.label, ok: ok, ms: Date.now() - t0, detail: detail });
      check(ok, { [s.label]: (v) => v === true });
      if (!ok) break;
    }
  } finally {
    await page.close();
  }
  console.log('EC_STEPS ' + JSON.stringify(results));
  console.log('EC_REQUESTS ' + JSON.stringify(requests.map((r) => ({ url: r.url.replace(BASE, ''), ms: r.ms, wall_ms: r.wall_ms, status: r.status }))));
}

export function handleSummary(data) {
  return { [__ENV.EC_SUMMARY]: JSON.stringify(data) };
}
"""

HTTP_TEMPLATE = r"""// Generated by evidence-council from persona "%(id)s" (%(name)s)%(load_note)s. Review before approving.
import http from 'k6/http';
import { check } from 'k6';

export const options = {
  scenarios: { journey: %(scenario)s },
  summaryTrendStats: ['avg', 'min', 'med', 'max', 'p(90)', 'p(95)'],
};

const BASE = __ENV.EC_BASE_URL;          // set by evidence-council: always http://127.0.0.1:<port>
const STEPS = %(steps)s;

export default function () {
  for (const s of STEPS) {
    const body = (s.body === undefined || s.body === null) ? null : JSON.stringify(s.body);
    const res = http.request(s.method, BASE + s.path, body, {
      headers: { 'Content-Type': 'application/json' }, timeout: s.timeout_ms + 'ms', tags: { step: s.label } });
    const text = String(res.body || '');
    const ok = check(res, { [s.label]: (r) => r.status === s.expect_status && (!s.contains || text.includes(s.contains)) });
    if (!ok) {
      console.log('EC_FAIL ' + JSON.stringify({ step: s.label, status: res.status, error: res.error || '', body: text.slice(0, 200) }));
    }
  }
}

export function handleSummary(data) {
  return { [__ENV.EC_SUMMARY]: JSON.stringify(data) };
}
"""


def _steps_json(steps: list[dict[str, Any]]) -> str:
    return json.dumps(steps, ensure_ascii=True, indent=2)


def render_persona(p: dict[str, Any], load: dict[str, Any] | None = None) -> str:
    if p["kind"] == "browser":
        total = sum(s.get("timeout_ms", 10000) for s in p["steps"]) // 1000 + 30
        return BROWSER_TEMPLATE % {"id": p["id"], "name": p["name"].replace("\n", " "), "steps": _steps_json(p["steps"]),
                                   "max_duration": min(total, 300)}
    if load:
        vus, dur = min(int(load["vus"]), 20), min(int(load["duration_s"]), 60)
        scenario = json.dumps({"executor": "constant-vus", "vus": vus, "duration": f"{dur}s", "gracefulStop": "5s"})
        note = f", load test \"{load['id']}\": {vus} users for {dur}s"
    else:
        scenario = json.dumps({"executor": "shared-iterations", "vus": 1, "iterations": 1, "maxDuration": "60s"})
        note = ""
    return HTTP_TEMPLATE % {"id": p["id"], "name": p["name"].replace("\n", " "), "steps": _steps_json(p["steps"]),
                            "scenario": scenario, "load_note": note}


def render_all(plan: dict[str, Any]) -> dict[str, str]:
    """{filename: script} for every persona and load test in the plan."""
    personas = {p["id"]: p for p in plan.get("personas", [])}
    out = {f"{p['id']}.js": render_persona(p) for p in personas.values()}
    for lo in plan.get("load", []):
        if lo["persona_id"] in personas:
            out[f"load-{lo['id']}.js"] = render_persona(personas[lo["persona_id"]], lo)
    return out


def write_scripts(plan: dict[str, Any], dest: Path) -> list[Path]:
    dest.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, text in render_all(plan).items():
        p = dest / name
        p.write_text(text, encoding="utf-8")
        paths.append(p)
    return paths


def k6_available() -> str | None:
    return shutil.which("k6")


def _metric(summary: dict[str, Any], name: str) -> dict[str, Any]:
    return (summary.get("metrics", {}).get(name) or {}).get("values", {})


def run_k6(script_path: Path, base_url: str, out_dir: Path, timeout_s: int) -> dict[str, Any]:
    """Run one k6 script against the local app; returns parsed results (never raises)."""
    if not base_url.startswith(("http://127.0.0.1:", "http://localhost:")):
        return {"status": "error", "error": f"refusing non-local target {base_url}"}
    k6 = k6_available()
    if not k6:
        return {"status": "not_run", "error": "k6 is not installed (brew install k6)"}
    out_dir.mkdir(parents=True, exist_ok=True)
    summary_path = out_dir / (script_path.stem + ".summary.json")
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin:/usr/local/bin"), "HOME": str(out_dir), "EC_BASE_URL": base_url,
           "EC_SUMMARY": str(summary_path), "K6_BROWSER_HEADLESS": "true", "K6_NO_USAGE_REPORT": "true",
           "TMPDIR": str(out_dir), "LANG": "en_US.UTF-8"}
    t0 = time.monotonic()
    try:
        r = subprocess.run([k6, "run", "--quiet", "--no-color", "--log-format=json", str(script_path)], capture_output=True, text=True,
                           timeout=timeout_s, env=env, cwd=str(out_dir))
        rc, out, err, hung = r.returncode, r.stdout, r.stderr, False
    except subprocess.TimeoutExpired as e:
        rc, out, err, hung = None, (e.stdout or b"").decode() if isinstance(e.stdout, bytes) else (e.stdout or ""), "", True
    dur = time.monotonic() - t0
    logs = []
    for line in (err + "\n" + out).splitlines():
        line = line.strip()
        if line.startswith("{"):
            try:
                logs.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    msgs = [str(x.get("msg", "")) for x in logs]
    steps: list[dict[str, Any]] = []
    fails: list[dict[str, Any]] = []
    req_log: list[dict[str, Any]] = []
    for m in msgs:
        if m.startswith("EC_STEPS "):
            try:
                steps = json.loads(m[9:])
            except json.JSONDecodeError:
                pass
        elif m.startswith("EC_REQUESTS "):
            try:
                req_log = json.loads(m[12:])
            except json.JSONDecodeError:
                pass
        elif m.startswith("EC_FAIL "):
            try:
                fails.append(json.loads(m[8:]))
            except json.JSONDecodeError:
                pass
    errors = [m for x, m in zip(logs, msgs) if x.get("level") in ("error", "fatal") and not m.startswith("EC_")
              and "unexpectedly ended" not in m][:5]   # Chrome being killed at shutdown is normal
    summary = {}
    if summary_path.exists():
        try:
            summary = json.loads(summary_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            summary = {}
    res: dict[str, Any] = {"script": script_path.name, "exit_code": rc, "duration_s": round(dur, 2), "steps": steps,
                           "failures": fails[:10], "k6_errors": errors, "hung": hung, "request_log": req_log[:200]}
    if hung:
        res["status"] = "hung"
        res["error"] = f"k6 did not finish within {timeout_s}s"
        return res
    if not summary:
        res["status"] = "error"
        res["error"] = "k6 produced no summary: " + "; ".join(errors or [err.strip()[-300:]])
        return res
    checks = _metric(summary, "checks")
    iters = _metric(summary, "iterations").get("count", 0) or 0
    res["checks"] = {"passes": checks.get("passes", 0), "fails": checks.get("fails", 0)}
    res["iterations"] = iters
    if "browser_http_req_duration" in summary.get("metrics", {}) or "browser_http_req_failed" in summary.get("metrics", {}):
        bf = _metric(summary, "browser_http_req_failed")
        bd = _metric(summary, "browser_http_req_duration")
        res["requests"] = int((bf.get("passes", 0) or 0) + (bf.get("fails", 0) or 0))
        res["failed_request_rate"] = bf.get("rate", 0)
        res["max_request_ms"] = bd.get("max")
        res["p95_ms"] = bd.get("p(95)")
    else:
        hr = _metric(summary, "http_reqs")
        hd = _metric(summary, "http_req_duration")
        hf = _metric(summary, "http_req_failed")
        res["requests"] = int(hr.get("count", 0) or 0)
        res["failed_request_rate"] = hf.get("rate", 0)
        res["max_request_ms"] = hd.get("max")
        res["p95_ms"] = hd.get("p(95)")
    res["requests_per_iteration"] = round(res["requests"] / iters, 2) if iters else None
    res["status"] = "ok"
    return res


def judge_journey(persona: dict[str, Any], r: dict[str, Any]) -> tuple[str, list[str]]:
    """Return (passed|failed|hung|not_run|error, reasons)."""
    if r["status"] in ("not_run", "error", "hung"):
        return r["status"], [r.get("error", r["status"])]
    reasons = []
    if persona["kind"] == "browser":
        bad = [s for s in r.get("steps", []) if not s.get("ok")]
        if bad:
            reasons += [f"step '{s['step']}' failed: {s.get('detail', '')}" for s in bad]
        elif len(r.get("steps", [])) < len(persona["steps"]):
            reasons.append(f"only {len(r.get('steps', []))} of {len(persona['steps'])} steps ran" + (f" ({'; '.join(r['k6_errors'])})" if r.get("k6_errors") else ""))
    else:
        if r.get("checks", {}).get("fails"):
            reasons += [f"step '{f['step']}' got HTTP {f['status']}{' ' + f['error'] if f.get('error') else ''}: {f.get('body', '')[:120]}"
                        for f in r.get("failures", [])] or [f"{r['checks']['fails']} check(s) failed"]
    rpi = r.get("requests_per_iteration")
    log = r.get("request_log") or []
    if rpi is not None and rpi > persona["max_requests"]:
        top = ""
        if log:
            counts: dict[str, int] = {}
            for x in log:
                counts[x["url"]] = counts.get(x["url"], 0) + 1
            url, n = max(counts.items(), key=lambda kv: kv[1])
            top = f" ({url} requested {n} times)"
        reasons.append(f"unintended repeated work: {rpi:g} requests per journey, limit {persona['max_requests']}{top}")
    timed = [x for x in log if x.get("ms") is not None]
    if persona["kind"] == "browser" and timed:
        # per-request browser timing (sent -> first byte) excludes browser start-up; k6's whole-request metric does not
        slow = max(timed, key=lambda x: x["ms"])
        if slow["ms"] > persona["max_request_ms"]:
            reasons.append(f"slow or hanging request: {slow['url']} took {slow['ms']:.0f} ms to answer (HTTP {slow['status']}), "
                           f"limit {persona['max_request_ms']} ms")
    elif r.get("max_request_ms") is not None and r["max_request_ms"] > persona["max_request_ms"]:
        reasons.append(f"slow or hanging request: slowest took {r['max_request_ms']:.0f} ms, limit {persona['max_request_ms']} ms")
    return ("failed" if reasons else "passed"), reasons


def judge_load(load: dict[str, Any], persona: dict[str, Any], r: dict[str, Any]) -> tuple[str, list[str]]:
    if r["status"] in ("not_run", "error", "hung"):
        return r["status"], [r.get("error", r["status"])]
    reasons = []
    if (r.get("p95_ms") or 0) > load["p95_ms"]:
        reasons.append(f"p95 {r['p95_ms']:.0f} ms is above the {load['p95_ms']} ms limit")
    if (r.get("failed_request_rate") or 0) > load["max_error_rate"]:
        reasons.append(f"{r['failed_request_rate'] * 100:.1f}% of requests failed (limit {load['max_error_rate'] * 100:.0f}%)")
    if r.get("checks", {}).get("fails"):
        reasons.append(f"{r['checks']['fails']} response check(s) failed under load")
    rpi = r.get("requests_per_iteration")
    if rpi is not None and rpi > persona["max_requests"]:
        reasons.append(f"unintended repeated work: {rpi:g} requests per iteration, limit {persona['max_requests']}")
    if r.get("max_request_ms") is not None and r["max_request_ms"] > persona["max_request_ms"]:
        reasons.append(f"hanging request under load: slowest took {r['max_request_ms']:.0f} ms (limit {persona['max_request_ms']} ms)")
    return ("failed" if reasons else "passed"), reasons
